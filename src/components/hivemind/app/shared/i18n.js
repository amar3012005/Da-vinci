function getInitialLocale() {
  if (typeof window === 'undefined') return 'en';
  try {
    const stored = window.localStorage.getItem(STORAGE_KEY);
    if (stored && messages[stored]) return stored;
  } catch {}
  const browser = (navigator.language || 'en').slice(0, 2).toLowerCase();
  return messages[browser] ? browser : 'en';
}

const I18nContext = createContext(null);

export function I18nProvider({ children }) {
  const [locale, setLocaleState] = useState(getInitialLocale);

  useEffect(() => {
    if (typeof document !== 'undefined') {
      document.documentElement.lang = locale;
      document.documentElement.dir = RTL_LOCALES.has(locale) ? 'rtl' : 'ltr';
    }
    try {
      window.localStorage.setItem(STORAGE_KEY, locale);
    } catch {}
  }, [locale]);

  const setLocale = (next) => {
    if (messages[next]) setLocaleState(next);
  };

  const value = useMemo(() => ({
    locale,
    setLocale,
    messages: messages[locale] || messages.en,
    t: (path, fallback) => path.split('.').reduce((acc, key) => acc && acc[key], messages[locale]) ?? fallback ?? path,
    formatDate: (value, options = {}) => {
      if (!value) return '';
      return new Intl.DateTimeFormat(locale, options).format(new Date(value));
    },
    formatNumber: (value, options = {}) => {
      if (value === null || value === undefined) return '';
      return new Intl.NumberFormat(locale, options).format(value);
    },
    isRTL: RTL_LOCALES.has(locale),
  }), [locale]);

  return <I18nContext.Provider value={value}>{children}</I18nContext.Provider>;
}

export function useI18n() {
  const ctx = useContext(I18nContext);
  if (!ctx) throw new Error('useI18n must be used within I18nProvider');
  return ctx;
}

export const SUPPORTED_LOCALES = Object.keys(messages);
